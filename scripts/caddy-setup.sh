#!/usr/bin/env bash
# =============================================================================
# caddy-setup.sh — Install Caddy as TLS front-end and reverse proxy
#
# Usage:
#   chmod +x caddy-setup.sh
#   sudo ./caddy-setup.sh
#
# Prerequisites:
#   - wstunnel-server-setup.sh already run (generates /etc/wstunnel/secret-env)
#   - curl, openssl, apt installed
#   - TCP:443 open in the Lightsail panel (Networking → IPv4 Firewall)
#
# Architecture:
#   Internet → Caddy :443 (TLS termination)
#     ├── path /<secret>/*  → ws://127.0.0.1:8080  (wstunnel → WireGuard)
#     └── path /*           → http://127.0.0.1:9000 (personal web services)
#
# Certificate:
#   Self-signed EC P-256 generated in /etc/caddy/tls/
#   wstunnel clients use certificate pinning against this file.
#   wg-add-client.sh reads it from /etc/caddy/tls/cert.pem to include it
#   in the client package.
#
# Future migration to Let's Encrypt:
#   Replace the tls block in the Caddyfile with the ACME certificate path
#   and redistribute client packages with the new cert.pem.
#
# This script is idempotent.
# =============================================================================

set -euo pipefail

# ── Colors ────────────────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
BOLD='\033[1m'
NC='\033[0m'

info()    { echo -e "${BLUE}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
error()   { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }
section() { echo -e "\n${BOLD}━━━  $*  ━━━${NC}\n"; }

# ── Root check ────────────────────────────────────────────────────────────────
[[ $EUID -ne 0 ]] && error "Run with sudo: sudo ./caddy-setup.sh"

umask 077

# ── Configurable constants ────────────────────────────────────────────────────
CADDY_TLS_DIR="/etc/caddy/tls"
CADDY_CERT="${CADDY_TLS_DIR}/cert.pem"
CADDY_KEY="${CADDY_TLS_DIR}/key.pem"
CADDYFILE="/etc/caddy/Caddyfile"

# Secret source of truth — generated by wstunnel-server-setup.sh
SECRET_ENV_FILE="/etc/wstunnel/secret-env"

PUBLIC_PORT=443
WSTUNNEL_BACKEND="127.0.0.1:8080"

# Placeholder backend for personal web services.
# Replace with your application's port (Homer, Filebrowser, etc.)
WEBAPP_BACKEND="127.0.0.1:9000"

CERT_DAYS=825
SERVICE_OVERRIDE_DIR="/etc/systemd/system/caddy.service.d"

# =============================================================================
# Header
# =============================================================================

clear
echo -e "${BOLD}╔══════════════════════════════════════════╗${NC}"
echo -e "${BOLD}║    Caddy — TLS reverse proxy setup       ║${NC}"
echo -e "${BOLD}╚══════════════════════════════════════════╝${NC}"
echo ""

# =============================================================================
# Prerequisites
# =============================================================================

section "Prerequisites check"

command -v curl    > /dev/null || error "curl not found."
command -v openssl > /dev/null || error "openssl not found."

if [[ ! -f "$SECRET_ENV_FILE" ]]; then
  error "File not found: ${SECRET_ENV_FILE}\n\n  Run first:\n    sudo ./wstunnel-server-setup.sh"
fi

# shellcheck source=/dev/null
source "$SECRET_ENV_FILE"
[[ -z "${WSTUNNEL_SECRET:-}" ]] && \
  error "WSTUNNEL_SECRET empty in ${SECRET_ENV_FILE}."

success "Secret loaded: ${WSTUNNEL_SECRET:0:8}…"

if ! ss -tlnp | grep -q "${WSTUNNEL_BACKEND}"; then
  warn "wstunnel not listening on ${WSTUNNEL_BACKEND}."
  warn "Ensure wstunnel.service is active: sudo systemctl status wstunnel"
  read -rp "$(echo -e "${YELLOW}Continue anyway? [y/N]:${NC} ")" force_continue
  [[ "${force_continue,,}" == "y" ]] || exit 0
fi

success "Prerequisites verified"

# =============================================================================
# Public IP detection
# =============================================================================

section "Public IP detection"

get_public_ip() {
  local ip=""
  local token
  token=$(curl -s --max-time 3 -X PUT \
    "http://169.254.169.254/latest/api/token" \
    -H "X-aws-ec2-metadata-token-ttl-seconds: 21600" 2>/dev/null || true)
  if [[ -n "$token" ]]; then
    ip=$(curl -s --max-time 3 \
      -H "X-aws-ec2-metadata-token: $token" \
      "http://169.254.169.254/latest/meta-data/public-ipv4" 2>/dev/null || true)
  fi
  if [[ -z "$ip" ]]; then
    echo -e "${YELLOW}[WARN]${NC}  IMDSv2 unavailable — falling back to IMDSv1 (deprecated by AWS)." >&2
    ip=$(curl -s --max-time 3 \
      "http://169.254.169.254/latest/meta-data/public-ipv4" 2>/dev/null || true)
  fi
  [[ -z "$ip" ]] && ip=$(curl -s --max-time 5 "https://api.ipify.org" 2>/dev/null || true)
  echo "$ip"
}

SERVER_IP=$(get_public_ip)
[[ -z "$SERVER_IP" ]] && error "Cannot determine public IP."
success "Public IP: ${SERVER_IP}"

# =============================================================================
# Caddy installation
# =============================================================================

section "Caddy installation"

# Official Caddy repository — the Ubuntu apt package is outdated.
if command -v caddy > /dev/null 2>&1; then
  CADDY_INSTALLED_VER=$(caddy version 2>/dev/null | grep -oP 'v\d+\.\d+\.\d+' | head -1 || true)
  info "Caddy already installed: ${CADDY_INSTALLED_VER}"
else
  info "Installing Caddy from official repository..."
  apt-get install -y debian-keyring debian-archive-keyring apt-transport-https curl \
    > /dev/null 2>&1

  curl -s "https://dl.cloudsmith.io/public/caddy/stable/gpg.key" \
    | gpg --batch --yes --dearmor \
    -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg

  curl -s "https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt" \
    > /etc/apt/sources.list.d/caddy-stable.list

  apt-get update -qq
  apt-get install -y caddy

  CADDY_INSTALLED_VER=$(caddy version 2>/dev/null | grep -oP 'v\d+\.\d+\.\d+' | head -1 || true)
  success "Caddy ${CADDY_INSTALLED_VER} installed"
fi

# =============================================================================
# Self-signed TLS certificate
# =============================================================================

section "TLS certificate"

mkdir -p "$CADDY_TLS_DIR"
chmod 700 "$CADDY_TLS_DIR"

REGEN_CERT=false

if [[ -f "$CADDY_CERT" && -f "$CADDY_KEY" ]]; then
  # checkend 2592000 = 30 days in seconds
  if ! openssl x509 -in "$CADDY_CERT" -noout -checkend 2592000 > /dev/null 2>&1; then
    warn "Certificate expires within 30 days — regenerating."
    REGEN_CERT=true
  else
    CERT_CN=$(openssl x509 -in "$CADDY_CERT" -noout -subject 2>/dev/null \
      | grep -oP 'CN\s*=\s*\K[^\s,/]+' || echo "unknown")
    CERT_EXPIRY=$(openssl x509 -in "$CADDY_CERT" -noout -enddate 2>/dev/null \
      | cut -d= -f2 || true)
    success "Certificate valid (CN=${CERT_CN}, expires: ${CERT_EXPIRY})"

    if [[ "$CERT_CN" != "$SERVER_IP" ]]; then
      warn "Certificate CN (${CERT_CN}) ≠ current IP (${SERVER_IP})."
      read -rp "$(echo -e "${YELLOW}Regenerate? [y/N]:${NC} ")" regen
      [[ "${regen,,}" == "y" ]] && REGEN_CERT=true
    fi
  fi
else
  REGEN_CERT=true
fi

if [[ "$REGEN_CERT" == true ]]; then
  info "Generating self-signed RSA-4096 certificate (CN=${SERVER_IP})..."

  # subjectAltName=IP: required for OpenSSL 3+ and Go (wstunnel is written in Rust
  # but uses rustls which verifies SAN). Without SAN, certificate pinning fails
  # on modern clients even with --tls-ca-certificate.
  openssl req -x509 \
    -newkey ec \
    -pkeyopt ec_paramgen_curve:P-256 \
    -keyout "$CADDY_KEY" \
    -out    "$CADDY_CERT" \
    -days   "$CERT_DAYS" \
    -noenc \
    -subj   "/CN=${SERVER_IP}" \
    -addext "subjectAltName=IP:${SERVER_IP}" \
    2>/dev/null

  chmod 600 "$CADDY_KEY"
  chmod 644 "$CADDY_CERT"
  success "Certificate generated: ${CADDY_CERT}"

  CERT_EXPIRY=$(openssl x509 -in "$CADDY_CERT" -noout -enddate 2>/dev/null \
    | cut -d= -f2 || true)
  info "Expires: ${CERT_EXPIRY}"

  warn "⚠  Certificate regenerated — all wstunnel clients with certificate pinning"
  warn "   must receive the new package. Re-run wg-add-client.sh for each one."
fi

openssl x509 -in "$CADDY_CERT" -noout -subject -enddate 2>/dev/null | sed 's/^/  /'

# ── Permissions: caddy must read cert and key ─────────────────────────────────
chown root:caddy "$CADDY_TLS_DIR" "$CADDY_CERT" "$CADDY_KEY"
chmod 750 "$CADDY_TLS_DIR"
chmod 640 "$CADDY_KEY"
chmod 644 "$CADDY_CERT"

success "TLS permissions configured (caddy group)"

# =============================================================================
# systemd override: EnvironmentFile for WSTUNNEL_SECRET
# =============================================================================

section "systemd override"

# Add 'caddy' to the 'wstunnel' group to read secret-env
if id caddy > /dev/null 2>&1 && id wstunnel > /dev/null 2>&1; then
  usermod -aG wstunnel caddy
  success "User 'caddy' added to group 'wstunnel'"
elif ! id wstunnel > /dev/null 2>&1; then
  warn "Group 'wstunnel' not found — run wstunnel-server-setup.sh first"
fi

mkdir -p "$SERVICE_OVERRIDE_DIR"

# Drop-in override — does not modify the official service (upgrade-resistant)
cat > "${SERVICE_OVERRIDE_DIR}/env.conf" << EOF
[Service]
# Inject WSTUNNEL_SECRET into the Caddy process for the Caddyfile ({env.WSTUNNEL_SECRET})
EnvironmentFile=${SECRET_ENV_FILE}
EOF

success "Override written: ${SERVICE_OVERRIDE_DIR}/env.conf"

# =============================================================================
# Caddyfile
# =============================================================================

section "Writing Caddyfile"

if [[ -f "$CADDYFILE" ]]; then
  BACKUP="${CADDYFILE}.bak.$(date +%Y%m%d_%H%M%S)"
  cp "$CADDYFILE" "$BACKUP"
  info "Backup: ${BACKUP}"
fi

# Note: the Caddyfile uses a single-quote heredoc ('CADDYEOF') to prevent bash
# from expanding ${ } — Caddy variables like {env.WSTUNNEL_SECRET} must arrive
# literally in the file and are expanded by Caddy at runtime.
cat > "$CADDYFILE" << 'CADDYEOF'
# =============================================================================
# Caddyfile — TLS reverse proxy for wstunnel + web services
#
# WSTUNNEL_SECRET is injected by systemd via EnvironmentFile.
# Do not manually edit the secret value here — it is read from
# /etc/wstunnel/secret-env which is the centralised source of truth.
#
# To update the secret:
#   1. rm /etc/wstunnel/secret && sudo ./wstunnel-server-setup.sh
#   2. sudo systemctl restart wstunnel caddy
#   3. Redistribute client packages (wg-add-client.sh)
# =============================================================================

:443 {
    # TLS with self-signed certificate.
    # Source of truth for wstunnel client certificate pinning.
    tls /etc/caddy/tls/cert.pem /etc/caddy/tls/key.pem {
        protocols tls1.3
    }

    # ── wstunnel routing ─────────────────────────────────────────────────────
    # Match: path starting with /<secret>/
    # The path is passed intact to wstunnel — wstunnel independently verifies
    # the prefix with --restrict-http-upgrade-path-prefix (second check).
    handle /{env.WSTUNNEL_SECRET}/* {
        reverse_proxy 127.0.0.1:8080 {
            # Disable response buffering — required for WebSocket.
            # Without this Caddy accumulates data before sending, breaking
            # the bidirectional flow of the WireGuard tunnel.
            flush_interval -1

            # Forward WebSocket upgrade headers to the backend
            header_up Connection {http.request.header.Connection}
            header_up Upgrade {http.request.header.Upgrade}

            # Force HTTP/1.1 to the backend — WebSocket is not compatible with HTTP/2
            transport http {
                versions h1
            }
        }
    }

    # ── Personal web services routing (fallback) ─────────────────────────────
    # Everything that does not contain the secret in the path goes to your apps.
    # 502 Bad Gateway if :9000 is not in use — correct and expected behaviour.
    handle /* {
        reverse_proxy 127.0.0.1:9000
    }
}
CADDYEOF

success "Caddyfile written: ${CADDYFILE}"

info "Validating Caddyfile..."
if caddy validate --config "$CADDYFILE" > /dev/null 2>&1; then
  success "Caddyfile valid"
else
  error "Caddyfile invalid:\n$(caddy validate --config "$CADDYFILE" 2>&1)"
fi

# =============================================================================
# Firewall
# =============================================================================

section "Firewall"

if command -v ufw > /dev/null && ufw status | grep -q "Status: active"; then
  if ! ufw status | grep -q "${PUBLIC_PORT}/tcp"; then
    ufw allow "${PUBLIC_PORT}/tcp" comment "Caddy HTTPS"
    success "ufw rule added: TCP:${PUBLIC_PORT}"
  else
    success "ufw rule TCP:${PUBLIC_PORT} already present"
  fi
else
  warn "ufw not active — manual firewall management required"
fi

echo ""
warn "Remember: open TCP:${PUBLIC_PORT} in the Lightsail panel if not already done:"
warn "  Instance → Networking → IPv4 Firewall → Add rule → TCP ${PUBLIC_PORT}"

# =============================================================================
# Start Caddy
# =============================================================================

section "Starting Caddy service"

systemctl daemon-reload

if systemctl is-active --quiet caddy 2>/dev/null; then
  systemctl reload caddy 2>/dev/null || systemctl restart caddy
  success "caddy.service reloaded"
else
  systemctl enable --now caddy
  success "caddy.service enabled and started"
fi

for i in {1..10}; do
  systemctl is-active --quiet caddy && break
  sleep 1
done
if systemctl is-active --quiet caddy; then
  success "caddy.service active"
else
  error "caddy.service failed to start.\n  Check: journalctl -u caddy -n 30"
fi

# =============================================================================
# End-to-end verification
# =============================================================================

section "Connectivity check"

# Test 1: Caddy responds on :443
info "Local TLS test on 127.0.0.1:${PUBLIC_PORT}..."
TLS_RESULT=$(curl -sk --max-time 5 -o /dev/null -w "%{http_code}" \
  "https://127.0.0.1:${PUBLIC_PORT}" 2>/dev/null || true)

if [[ "$TLS_RESULT" =~ ^[0-9]+$ ]]; then
  success "Caddy responds on :${PUBLIC_PORT} (HTTP ${TLS_RESULT})"
else
  warn "No response — check: journalctl -u caddy -n 20"
fi

# Test 2: secret path → wstunnel (expect 400 or 101, not 404)
info "Testing routing /${WSTUNNEL_SECRET:0:8}…/ → wstunnel..."
SECRET_RESULT=$(curl -sk --max-time 5 -o /dev/null -w "%{http_code}" \
  "https://127.0.0.1:${PUBLIC_PORT}/${WSTUNNEL_SECRET}/" 2>/dev/null || true)

case "$SECRET_RESULT" in
  101|400|200) success "Secret routing → wstunnel OK (HTTP ${SECRET_RESULT})" ;;
  404)         warn    "404 received — check path in Caddyfile and secret." ;;
  *)           info    "Secret routing: HTTP ${SECRET_RESULT}" ;;
esac

# Test 3: path without secret → fallback (502 expected if :9000 is not in use)
info "Testing routing / → webapp backend..."
FALLBACK_RESULT=$(curl -sk --max-time 5 -o /dev/null -w "%{http_code}" \
  "https://127.0.0.1:${PUBLIC_PORT}/" 2>/dev/null || true)

case "$FALLBACK_RESULT" in
  502) success "Fallback routing OK (502 — no service on :9000, expected)" ;;
  *)   success "Fallback routing: HTTP ${FALLBACK_RESULT}" ;;
esac

# =============================================================================
# Summary
# =============================================================================

section "Caddy setup complete"

echo -e "  Version      : ${BOLD}$(caddy version 2>/dev/null | grep -oP 'v\d+\.\d+\.\d+' | head -1)${NC}"
echo -e "  Certificate  : ${BOLD}${CADDY_CERT}${NC}"
echo -e "                 ↑ sole source for client certificate pinning"
echo -e "  TLS key      : ${BOLD}${CADDY_KEY}${NC}"
echo -e "  Caddyfile    : ${BOLD}${CADDYFILE}${NC}"
echo -e "  Port         : ${BOLD}TCP:${PUBLIC_PORT}${NC}"
echo ""
echo -e "  Routing:"
echo -e "    /${WSTUNNEL_SECRET:0:8}…/* → ${BOLD}ws://${WSTUNNEL_BACKEND}${NC} (wstunnel)"
echo -e "    /*            → ${BOLD}http://${WEBAPP_BACKEND}${NC} (webapp — 502 if not active)"
echo ""
echo -e "  ${YELLOW}wg-add-client.sh${NC} will read the certificate from ${BOLD}${CADDY_CERT}${NC}"
echo ""
echo -e "${GREEN}Service status:${NC}"
systemctl status caddy wstunnel --no-pager -l | head -25
